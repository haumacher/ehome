#!/bin/sh
# TLS for a development E-Home without a public host (doc/controllers.md "TLS during development"):
# a local CA, a server certificate for this machine's addresses and nginx in docker in front of the
# E-Home started with `./mvnw -pl ehome exec:java`, configured like the production proxy.
#
#   bin/dev-tls.sh start [port]   # https://<this machine>:<port>/ehome (default 8443) -> localhost:8080
#   bin/dev-tls.sh stop
#   bin/dev-tls.sh ca             # prints the path of the CA certificate (PEM)
#
# The CA and the server key live in ${EHOME_DEV_TLS:-~/.config/ehome/dev-tls}, outside the
# repository; the keys are private (mode 600). The server certificate names localhost, the host
# name, <host name>.local and every IPv4 address of this machine; `start` issues it again when an
# address is missing (a new DHCP lease). A HomeControl controller trusts the CA when its firmware is
# built with -DHC_EXTRA_CA=<the CA certificate> (homecontrol doc/ehome.md).
set -eu

dir=${EHOME_DEV_TLS:-$HOME/.config/ehome/dev-tls}
name=ehome-dev-tls
backend=${EHOME_DEV_BACKEND:-127.0.0.1:8080}

ca() {
	mkdir -p "$dir"
	chmod 700 "$dir"
	if [ ! -f "$dir/ca.key" ]; then
		(umask 077 && openssl ecparam -name prime256v1 -genkey -noout -out "$dir/ca.key")
		openssl req -x509 -new -key "$dir/ca.key" -sha256 -days 3650 \
			-subj "/CN=E-Home development CA ($(hostname))" \
			-addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
			-addext "keyUsage=critical,keyCertSign,cRLSign" \
			-out "$dir/ca.pem"
	fi
}

addresses() {
	hostname -I | tr ' ' '\n' | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | grep -v '^172\.17\.'
}

san() {
	printf 'DNS:localhost,DNS:%s,DNS:%s.local,IP:127.0.0.1' "$(hostname)" "$(hostname)"
	for ip in $(addresses); do
		printf ',IP:%s' "$ip"
	done
}

server_cert() {
	want=$(san)
	if [ -f "$dir/server.pem" ] && [ "$(cat "$dir/server.san" 2>/dev/null)" = "$want" ]; then
		return
	fi
	(umask 077 && openssl ecparam -name prime256v1 -genkey -noout -out "$dir/server.key")
	openssl req -new -key "$dir/server.key" -subj "/CN=$(hostname)" -out "$dir/server.csr"
	printf 'subjectAltName=%s\nbasicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth\n' \
		"$want" > "$dir/server.ext"
	openssl x509 -req -in "$dir/server.csr" -CA "$dir/ca.pem" -CAkey "$dir/ca.key" -CAcreateserial \
		-days 825 -sha256 -extfile "$dir/server.ext" -out "$dir/server.pem"
	printf '%s' "$want" > "$dir/server.san"
	rm -f "$dir/server.csr"
}

nginx_conf() {
	port=$1
	cat > "$dir/nginx.conf" <<EOF
# Generated by bin/dev-tls.sh: the proxy of doc/controllers.md "TLS is operations".
worker_processes 1;
error_log /dev/stderr warn;
pid /tmp/nginx.pid;
events { worker_connections 256; }
http {
	access_log /dev/stdout;
	client_max_body_size 64m;
	map \$http_upgrade \$connection_upgrade {
		default upgrade;
		'' close;
	}
	server {
		listen $port ssl;
		listen [::]:$port ssl;
		ssl_certificate /etc/ehome-dev-tls/server.pem;
		ssl_certificate_key /etc/ehome-dev-tls/server.key;
		location / {
			proxy_pass http://$backend;
			proxy_http_version 1.1;
			proxy_set_header Upgrade \$http_upgrade;
			proxy_set_header Connection \$connection_upgrade;
			proxy_set_header Host \$http_host;
			proxy_set_header X-Forwarded-Proto https;
			proxy_set_header X-Forwarded-Host \$http_host;
			proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
			proxy_read_timeout 120s;
			proxy_send_timeout 120s;
		}
	}
}
EOF
}

case "${1:-}" in
start)
	port=${2:-8443}
	ca
	server_cert
	nginx_conf "$port"
	docker rm -f "$name" >/dev/null 2>&1 || true
	# The container's nginx runs as root and reads the private key through the mount.
	docker run -d --name "$name" --network host -v "$dir:/etc/ehome-dev-tls:ro" \
		-v "$dir/nginx.conf:/etc/nginx/nginx.conf:ro" nginx:1.27-alpine >/dev/null
	sleep 1
	docker logs "$name" 2>&1 | grep -E 'emerg|error' && exit 1
	for ip in $(addresses); do
		echo "https://$ip:$port/ehome"
	done
	echo "CA: $dir/ca.pem"
	;;
stop)
	docker rm -f "$name" >/dev/null
	;;
ca)
	ca
	echo "$dir/ca.pem"
	;;
*)
	sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
	exit 2
	;;
esac
