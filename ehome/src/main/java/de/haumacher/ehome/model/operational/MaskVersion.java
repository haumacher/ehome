package de.haumacher.ehome.model.operational;

import java.util.List;
import java.util.Objects;

import com.top_logic.model.TLClassifier;

/**
 * Interface for {@link #MASK_VERSION_TYPE} business objects.
 * 
 * <p>
 * The features, resources, memory areas and generic load procedures of a mask version are kept in its
 * {@link #getConfigurations() configurations}. What is in effect for a program is its
 * {@link #getConfiguration(Program) configuration}: the {@link #getCurrentConfiguration() current
 * one}, or on a mask describing itself once per programming style of the line couplers, the one of
 * the program's style. The accessors with a program read those of that configuration.
 * </p>
 * 
 * @author Automatically generated by {@link com.top_logic.element.model.generate.InterfaceTemplateGenerator}
 */
public interface MaskVersion extends de.haumacher.ehome.model.operational.internal.MaskVersionBase {

	/**
	 * The feature of a configuration whose load state machines are controlled through properties.
	 */
	String PROPERTY_MAPPED_LSMS = "PropertyMappedLsms";

	/**
	 * The management model of a mask managed as BCU 1 (the masks 001x and the couplers 09xx).
	 */
	String BCU1_MANAGEMENT = "Bcu1";

	/**
	 * The current configuration of this mask version: the first one not marked legacy, <code>null</code> if
	 * the mask version has none. It is what a device of the mask is described by when no program is
	 * known; for a program, see {@link #getConfiguration(Program)}.
	 */
	default MaskConfiguration getCurrentConfiguration() {
		for (MaskConfiguration configuration : getConfigurations()) {
			if (!Boolean.TRUE.equals(configuration.getLegacyOrNull())) {
				return configuration;
			}
		}
		return null;
	}

	/**
	 * The configuration in effect for the given program, <code>null</code> if the mask version has none.
	 * 
	 * <p>
	 * The masks of the line couplers 0912 and 091A describe themselves twice, once per programming style
	 * of the program (ETS: <code>Options@LineCoupler0912NewProgrammingStyle</code>, comments in
	 * <code>knx_master.xml</code>): the new style with load state machines controlled through
	 * properties (feature {@value #PROPERTY_MAPPED_LSMS} 1), the old style without, its load
	 * controls in memory. Which of the two the master data mark legacy depends on their version (ETS
	 * 4: the new style, ETS 6: the old style of 091A), so on a mask {@link #BCU1_MANAGEMENT managed as
	 * BCU 1} with a configuration of each kind, the program's
	 * {@link Program#getLineCouplerNewProgrammingStyle() style} selects it (haumacher/ehome #229).
	 * Otherwise, and without a program, the {@link #getCurrentConfiguration() current configuration}.
	 * </p>
	 */
	default MaskConfiguration getConfiguration(Program program) {
		MaskConfiguration current = getCurrentConfiguration();
		if (program == null || current == null || getConfigurations().size() < 2) {
			return current;
		}
		TLClassifier model = getManagementModel();
		if (model == null || !BCU1_MANAGEMENT.equals(model.getName())) {
			return current;
		}
		boolean newStyle = Boolean.TRUE.equals(program.getLineCouplerNewProgrammingStyleOrNull());
		MaskConfiguration byProperties = null;
		MaskConfiguration inMemory = null;
		for (MaskConfiguration configuration : getConfigurations()) {
			if (propertyMapped(configuration)) {
				if (byProperties == null) {
					byProperties = configuration;
				}
			} else if (inMemory == null) {
				inMemory = configuration;
			}
		}
		if (byProperties == null || inMemory == null) {
			return current;
		}
		return newStyle ? byProperties : inMemory;
	}

	/**
	 * Whether the load state machines of the given configuration are controlled through properties
	 * (feature {@value #PROPERTY_MAPPED_LSMS} 1); <code>false</code> for no configuration.
	 */
	static boolean propertyMapped(MaskConfiguration configuration) {
		if (configuration == null) {
			return false;
		}
		for (MaskFeature feature : configuration.getFeatures()) {
			if (PROPERTY_MAPPED_LSMS.equals(feature.getName()) && Objects.equals(feature.getValue(), 1)) {
				return true;
			}
		}
		return false;
	}

	/**
	 * The features of the {@link #getConfiguration(Program) configuration} for the given program.
	 */
	default List<? extends MaskFeature> getFeatures(Program program) {
		MaskConfiguration configuration = getConfiguration(program);
		return configuration == null ? List.of() : configuration.getFeatures();
	}

	/**
	 * The resources of the {@link #getConfiguration(Program) configuration} for the given program.
	 */
	default List<? extends MaskResource> getResources(Program program) {
		MaskConfiguration configuration = getConfiguration(program);
		return configuration == null ? List.of() : configuration.getResources();
	}

	/**
	 * The memory areas of the {@link #getConfiguration(Program) configuration} for the given program.
	 */
	default List<? extends MaskMemory> getMemory(Program program) {
		MaskConfiguration configuration = getConfiguration(program);
		return configuration == null ? List.of() : configuration.getMemory();
	}

	/**
	 * The generic load procedures of the {@link #getConfiguration(Program) configuration} for the given
	 * program.
	 */
	default List<? extends LoadProcedure> getProcedures(Program program) {
		MaskConfiguration configuration = getConfiguration(program);
		return configuration == null ? List.of() : configuration.getProcedures();
	}

}
