package test.de.haumacher.ehome.model;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Map.Entry;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * The scan of a module's Java sources for name-based model access with a literal attribute name
 * (haumacher/ehome #198), checked against the module's inventory {@value #INVENTORY}.
 *
 * <p>
 * Model access goes through the generated interfaces of the model (<code>tl:generate-java</code>,
 * packages <code>de.haumacher.ehome.model.*</code>). A call <code>tValueByName("…")</code>,
 * <code>tUpdateByName("…", …)</code>, <code>tAddByName("…", …)</code> or
 * <code>tRemoveByName("…", …)</code> whose first argument is a string literal names an attribute
 * the compiler does not check. The scan counts these calls per file in <code>src/main/java</code>
 * and <code>src/test/java</code> of a module (comments do not count, a call may span lines, the
 * receiver does not matter), leaving out the generated code (<code>model/**&#47;internal/</code>, the
 * factories <code>model/*&#47;*Factory.java</code>).
 * </p>
 *
 * <p>
 * The inventory has two sections of lines <code>&lt;path&gt; = &lt;count&gt;</code>, the path
 * relative to the module directory:
 * </p>
 * <ul>
 * <li><code>[generic]</code>: the legitimate generic places, code that works on objects of arbitrary
 * types by their model (the ETS import's mapping, the <code>.knxproj</code> export, the project file
 * <code>.ehome</code>, the generic copy and merge). They keep the generic API permanently; an entry
 * stays when its count drops to 0.</li>
 * <li><code>[migrate]</code>: the calls waiting for their move to the generated accessors. The
 * section is a ratchet: a file must have exactly its count, so a new call fails, and a migration
 * lowers the entry (a file at 0 drops out).</li>
 * </ul>
 *
 * <p>
 * The inventory is regenerated from the sources by {@link #regenerate(File)}: the test with the
 * system property {@value #REGENERATE_PROPERTY} (<code>./mvnw test -DskipTests=false
 * -Dtest=TestNameAccess -Dehome.nameAccess.regenerate=true</code> in the module) or
 * {@link #main(String[])}. It keeps the files of the generic section and counts every file again.
 * </p>
 */
public final class NameAccessScan {

	/** The inventory, relative to the module directory. */
	public static final String INVENTORY = "src/test/name-access-inventory.txt";

	/** The system property that makes the test write the inventory instead of checking it. */
	public static final String REGENERATE_PROPERTY = "ehome.nameAccess.regenerate";

	private static final String GENERIC = "generic";

	private static final String MIGRATE = "migrate";

	private static final String[] SOURCE_DIRS = { "src/main/java", "src/test/java" };

	private static final Pattern CALL = Pattern.compile("\\bt(?:Value|Update|Add|Remove)ByName\\s*\\(\\s*\"");

	private static final Pattern ENTRY = Pattern.compile("^\\s*(\\S+)\\s*=\\s*(\\d+)\\s*$");

	private static final Pattern SECTION = Pattern.compile("^\\s*\\[(\\w+)\\]\\s*$");

	private NameAccessScan() {
		// Static utility.
	}

	/**
	 * The name-based calls with a literal name in the sources of the given module, per file (path
	 * relative to the module directory, with <code>/</code>): the line numbers of the calls.
	 */
	public static Map<String, List<Integer>> scan(File moduleDir) throws IOException {
		Map<String, List<Integer>> result = new TreeMap<>();
		Path base = moduleDir.toPath();
		for (String dir : SOURCE_DIRS) {
			Path root = base.resolve(dir);
			if (!Files.isDirectory(root)) {
				continue;
			}
			List<Path> sources;
			try (Stream<Path> files = Files.walk(root)) {
				sources = files.filter(p -> p.toString().endsWith(".java")).sorted().toList();
			}
			for (Path source : sources) {
				String path = base.relativize(source).toString().replace(File.separatorChar, '/');
				if (isGenerated(path)) {
					continue;
				}
				List<Integer> lines = calls(Files.readString(source, StandardCharsets.UTF_8));
				if (!lines.isEmpty()) {
					result.put(path, lines);
				}
			}
		}
		return result;
	}

	/**
	 * Whether the given source is generated by <code>tl:generate-java</code> (the hand-written
	 * interfaces <code>X.java</code> of the model packages are not).
	 */
	static boolean isGenerated(String path) {
		int model = path.indexOf("/de/haumacher/ehome/model/");
		if (model < 0) {
			return false;
		}
		String rest = path.substring(model);
		return rest.contains("/internal/") || rest.endsWith("Factory.java");
	}

	/**
	 * The lines (starting at 1) of the name-based calls with a literal name in the given Java source.
	 */
	public static List<Integer> calls(String source) {
		String code = stripComments(source);
		List<Integer> result = new ArrayList<>();
		Matcher matcher = CALL.matcher(code);
		while (matcher.find()) {
			int line = 1;
			for (int n = 0; n < matcher.start(); n++) {
				if (code.charAt(n) == '\n') {
					line++;
				}
			}
			result.add(line);
		}
		return result;
	}

	/**
	 * The source with its comments replaced by blanks (line breaks kept), its string and character
	 * literals and text blocks unchanged.
	 */
	static String stripComments(String source) {
		StringBuilder result = new StringBuilder(source.length());
		int n = 0;
		int length = source.length();
		while (n < length) {
			char c = source.charAt(n);
			if (source.startsWith("//", n)) {
				int end = source.indexOf('\n', n);
				n = end < 0 ? length : end;
			} else if (source.startsWith("/*", n)) {
				int end = source.indexOf("*/", n + 2);
				int stop = end < 0 ? length : end + 2;
				for (int k = n; k < stop; k++) {
					result.append(source.charAt(k) == '\n' ? '\n' : ' ');
				}
				n = stop;
			} else if (source.startsWith("\"\"\"", n)) {
				int end = source.indexOf("\"\"\"", n + 3);
				int stop = end < 0 ? length : end + 3;
				result.append(source, n, stop);
				n = stop;
			} else if (c == '"' || c == '\'') {
				int k = n + 1;
				while (k < length && source.charAt(k) != c && source.charAt(k) != '\n') {
					if (source.charAt(k) == '\\') {
						k++;
					}
					k++;
				}
				int stop = Math.min(k + 1, length);
				result.append(source, n, stop);
				n = stop;
			} else {
				result.append(c);
				n++;
			}
		}
		return result.toString();
	}

	/**
	 * The inventory of the given module: its sections by name, each the counts per path in the
	 * order of the file.
	 */
	public static Map<String, Map<String, Integer>> readInventory(File moduleDir) throws IOException {
		Map<String, Map<String, Integer>> result = new LinkedHashMap<>();
		result.put(GENERIC, new LinkedHashMap<>());
		result.put(MIGRATE, new LinkedHashMap<>());
		File file = new File(moduleDir, INVENTORY);
		if (!file.exists()) {
			return result;
		}
		Map<String, Integer> section = null;
		int number = 0;
		for (String line : Files.readAllLines(file.toPath(), StandardCharsets.UTF_8)) {
			number++;
			String content = line.strip();
			if (content.isEmpty() || content.startsWith("#")) {
				continue;
			}
			Matcher header = SECTION.matcher(content);
			if (header.matches()) {
				section = result.get(header.group(1));
				if (section == null) {
					throw new IOException(INVENTORY + ":" + number + ": unknown section '" + header.group(1) + "'.");
				}
				continue;
			}
			Matcher entry = ENTRY.matcher(content);
			if (!entry.matches() || section == null) {
				throw new IOException(INVENTORY + ":" + number + ": expected '[generic]', '[migrate]' or '<path> = <count>'.");
			}
			section.put(entry.group(1), Integer.valueOf(entry.group(2)));
		}
		return result;
	}

	/**
	 * The differences between the sources of the given module and its inventory; empty if they
	 * agree.
	 */
	public static List<String> check(File moduleDir) throws IOException {
		Map<String, List<Integer>> found = scan(moduleDir);
		Map<String, Map<String, Integer>> inventory = readInventory(moduleDir);
		Map<String, Integer> generic = inventory.get(GENERIC);
		Map<String, Integer> migrate = inventory.get(MIGRATE);
		List<String> problems = new ArrayList<>();
		for (String path : generic.keySet()) {
			if (migrate.containsKey(path)) {
				problems.add(path + ": listed in both sections of the inventory.");
			}
		}
		for (Entry<String, List<Integer>> file : found.entrySet()) {
			String path = file.getKey();
			int count = file.getValue().size();
			Integer allowed = generic.containsKey(path) ? generic.get(path) : migrate.get(path);
			if (allowed == null) {
				problems.add(path + ": " + count + " name-based calls with a literal name (lines " + file.getValue()
					+ "), none allowed: use the generated accessors of the model.");
			} else if (count > allowed.intValue()) {
				problems.add(path + ": " + count + " name-based calls with a literal name (lines " + file.getValue()
					+ "), " + allowed + " allowed: use the generated accessors of the model.");
			} else if (count < allowed.intValue()) {
				problems.add(path + ": " + count + " name-based calls with a literal name, the inventory allows "
					+ allowed + ": lower its entry to " + count + (count == 0 ? " (drop it)" : "") + ".");
			}
		}
		for (Map<String, Integer> section : List.of(generic, migrate)) {
			for (Entry<String, Integer> entry : section.entrySet()) {
				String path = entry.getKey();
				if (!new File(moduleDir, path).isFile()) {
					problems.add(path + ": in the inventory, but there is no such file.");
				} else if (!found.containsKey(path) && entry.getValue().intValue() > 0) {
					problems.add(path + ": no name-based call with a literal name any more, the inventory allows "
						+ entry.getValue() + ": "
						+ (section == generic ? "lower its entry to 0." : "drop its entry."));
				} else if (section == migrate && entry.getValue().intValue() == 0) {
					problems.add(path + ": an entry 0 in [migrate]: drop it.");
				}
			}
		}
		return problems;
	}

	/**
	 * Writes the inventory of the given module from its sources: the files of the generic section
	 * stay generic, every other file with calls goes into the migration section.
	 */
	public static void regenerate(File moduleDir) throws IOException {
		Map<String, List<Integer>> found = scan(moduleDir);
		Map<String, Integer> generic = readInventory(moduleDir).get(GENERIC);
		StringBuilder out = new StringBuilder();
		out.append("# Name-based model access with a literal attribute name (haumacher/ehome #198): the calls\n");
		out.append("# t(Value|Update|Add|Remove)ByName(\"...\") per source file of this module, checked by\n");
		out.append("# TestNameAccess (test.de.haumacher.ehome.model.NameAccessScan). Model access goes through the\n");
		out.append("# generated interfaces (de.haumacher.ehome.model.*).\n");
		out.append("#\n");
		out.append("# [generic]: the legitimate generic places (code working on arbitrary types by their model);\n");
		out.append("# they keep the generic API permanently, a migration leaves them.\n");
		out.append("# [migrate]: a ratchet; a file must have exactly its count. After moving calls to the\n");
		out.append("# generated accessors, lower the entry (a file at 0 drops out): by hand, or regenerate with\n");
		out.append("#   ./mvnw test -DskipTests=false -Dtest=TestNameAccess -Dehome.nameAccess.regenerate=true\n");
		out.append("# in the module directory, and check the diff: no entry may grow.\n");
		out.append("\n[" + GENERIC + "]\n");
		for (String path : generic.keySet()) {
			if (new File(moduleDir, path).isFile()) {
				List<Integer> lines = found.get(path);
				out.append(path + " = " + (lines == null ? 0 : lines.size()) + "\n");
			}
		}
		out.append("\n[" + MIGRATE + "]\n");
		for (Entry<String, List<Integer>> file : found.entrySet()) {
			if (!generic.containsKey(file.getKey())) {
				out.append(file.getKey() + " = " + file.getValue().size() + "\n");
			}
		}
		Files.writeString(new File(moduleDir, INVENTORY).toPath(), out.toString(), StandardCharsets.UTF_8);
	}

	/**
	 * Regenerates the inventory of each module directory given (default: the current directory).
	 */
	public static void main(String[] args) throws IOException {
		String[] dirs = args.length == 0 ? new String[] { "." } : args;
		for (String dir : dirs) {
			regenerate(new File(dir));
		}
	}

}
